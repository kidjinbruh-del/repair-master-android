def panel(x, y, w, h, title, rows, color=FRAME, title_color=AMBER):
    p = [rect(x, y, w, h, fill="#151B27", stroke=color, rx=14)]
    if title:
        p.append(text(x + 16, y + 26, title, 15, title_color, weight="700"))
    for i, r in enumerate(rows):
        p.append(text(x + 16, y + 52 + i * 22, r, 13, MUTED))
    return "".join(p)


def bullets(x, y, items, color=CYAN, step=26, size=14):
    return "".join(
        f'<circle cx="{x}" cy="{y + i * step - 5}" r="4" fill="{color}"/>'
        + text(x + 16, y + i * step, t, size, TEXT)
        for i, t in enumerate(items)
    )


