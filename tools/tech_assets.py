def device(cx, cy, w, h, label, screen=None, keys=3, color=FRAME):
    p = [rect(cx - w / 2, cy - h / 2, w, h, fill="#1B2233", stroke=color, sw=3, rx=14)]
    if screen:
        p.append(rect(cx - w / 2 + 16, cy - h / 2 + 14, w - 32, h * 0.34,
                      fill="#0B1220", stroke=FRAME, rx=6))
        p.append(text(cx - w / 2 + 26, cy - h / 2 + 34, screen, 14, CYAN))
    for i in range(keys):
        p.append(circle(cx - 22 + i * 22, cy + h / 2 - 26, 6, fill="#2A3550", stroke=FRAME))
    if label:
        p.append(text(cx, cy + h / 2 + 22, label, 14, MUTED, "middle"))
    return "".join(p)


def motor(cx, cy, r=52):
    return "".join([
        rect(cx - r - 14, cy - r - 14, 2 * r + 28, 2 * r + 28, fill="#1B2233",
             stroke=FRAME, rx=16),
        circle(cx, cy, r, fill="#232C42", stroke=AMBER, sw=3),
        text(cx, cy - 8, "M", 34, AMBER, "middle", "700"),
        text(cx, cy + 22, "двигатель", 12, MUTED, "middle"),
        line(cx - r - 40, cy, cx - r - 16, cy, FRAME, 4),
        line(cx + r + 16, cy, cx + r + 40, cy, FRAME, 4),
    ])


def board(cx, cy, w=300, h=200, label="плата"):
    p = [rect(cx - w / 2, cy - h / 2, w, h, fill="#1D5C41", stroke=FRAME, rx=10)]
    for x in range(int(cx - w / 2 + 30), int(cx + w / 2 - 20), 34):
        p.append(line(x, cy - h / 2 + 12, x, cy + h / 2 - 12, "#2E7C5A", 2))
    p.append(rect(cx - 40, cy - 34, 80, 60, fill="#141A26", stroke=FRAME, rx=6))
    p.append(text(cx, cy + 2, "IC", 16, TEXT, "middle", "700"))
    p.append(rect(cx + 60, cy - 20, 30, 40, fill="#D8C39A", stroke=BODY_DK, rx=4))
    p.append(text(cx, cy + h / 2 + 22, label, 14, MUTED, "middle"))
    return "".join(p)


